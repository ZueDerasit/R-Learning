# R Basics: Vectors

# Creating a numeric vector
ages <- c(20, 25, 30, 35, 25)

# Creating a character vector
names <- c("Ali", "Siti", "John", "Mei", "Maria")

# Display the vectors
ages
names

# Check the length of a vector
length(ages)
length(names)

# Access an element using its position
ages[1]
ages[3]

names[2]
names[5]
