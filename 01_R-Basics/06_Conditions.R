# R Basics: Conditions

# Create a score
score <- 75

# If statement
if (score >= 50) {
  print("Pass")
}

# If...else statement
if (score >= 50) {
  print("Pass")
} else {
  print("Fail")
}

# If...else if...else statement
if (score >= 80) {
  print("Excellent")
} else if (score >= 50) {
  print("Pass")
} else {
  print("Fail")
}
